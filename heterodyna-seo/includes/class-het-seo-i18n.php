/**
 * Lightweight open-source UI language layer.
 *
 * This build intentionally avoids external translation services and remote calls.
 * The selected language is stored locally in HET_SEO_OPT['language'].
 */
class HET_SEO_I18N {
    const DEFAULT_LANG = 'pl';

    public static function languages(): array {
        return [
            'pl' => 'Polski',
            'en' => 'English',
            'ru' => 'Русский',
        ];
    }

    public static function language(): string {
        $opts = get_option(HET_SEO_OPT, []);
        $lang = is_array($opts) && isset($opts['language']) ? sanitize_key((string)$opts['language']) : self::DEFAULT_LANG;
        return array_key_exists($lang, self::languages()) ? $lang : self::DEFAULT_LANG;
    }

    public static function set_language_from_post(array &$opts): void {
        $lang = isset($_POST['het_seo_language']) ? sanitize_key((string)$_POST['het_seo_language']) : self::DEFAULT_LANG;
        $opts['language'] = array_key_exists($lang, self::languages()) ? $lang : self::DEFAULT_LANG;
    }

    public static function select_field(): void {
        $current = self::language();
        echo '<select name="het_seo_language">';
        foreach (self::languages() as $code => $label) {
            echo '<option value="' . esc_attr($code) . '" ' . selected($current, $code, false) . '>' . esc_html($label) . '</option>';
        }
        echo '</select>';
        echo '<p class="description">' . esc_html(self::t('Zmienia język panelu administracyjnego Heterodyna SEO.')) . '</p>';
    }

    public static function t(string $text): string {
        $lang = self::language();
        if ($lang === self::DEFAULT_LANG) { return $text; }
        $dict = self::dictionary($lang);
        return $dict[$text] ?? $text;
    }

    public static function start_admin_buffer(): void {
        if (!is_admin()) { return; }
        $page = isset($_GET['page']) ? sanitize_key((string)$_GET['page']) : '';
        $is_plugin_page = ($page === 'het_seo_center' || strpos($page, 'het_seo_') === 0);
        $is_editor = in_array($GLOBALS['pagenow'] ?? '', ['post.php', 'post-new.php'], true);
        if (!$is_plugin_page && !$is_editor) { return; }
        if (self::language() === self::DEFAULT_LANG) { return; }
        ob_start([__CLASS__, 'translate_html']);
    }

    public static function translate_html(string $html): string {
        $lang = self::language();
        if ($lang === self::DEFAULT_LANG || $html === '') { return $html; }

        $dict = self::html_dictionary($lang);
        if (empty($dict)) { return $html; }

        uksort($dict, static function($a, $b) {
            return strlen((string)$b) <=> strlen((string)$a);
        });

        /*
         * Do not run strtr() on the whole admin page.
         * The previous build translated inside HTML attributes, URLs, CSS classes,
         * JavaScript and WordPress admin links. In Russian mode short Polish words
         * such as "po" could corrupt markup/URLs and make the plugin page appear
         * broken or blank.
         *
         * We translate only visible text nodes and skip script/style/tag chunks.
         */
        $parts = preg_split('/(<script\b[^>]*>.*?<\/script>|<style\b[^>]*>.*?<\/style>|<[^>]+>)/is', $html, -1, PREG_SPLIT_DELIM_CAPTURE);
        if (!is_array($parts)) {
            return strtr($html, $dict);
        }

        foreach ($parts as $i => $part) {
            if ($part === '' || $part[0] === '<') {
                continue;
            }
            $parts[$i] = strtr($part, $dict);
        }

        return implode('', $parts);
    }

    private static function html_dictionary(string $lang): array {
        $dict = self::dictionary($lang);
        $safe = [];

        foreach ($dict as $from => $to) {
            if (!is_string($from) || !is_string($to)) { continue; }
            $from = trim($from);
            if ($from === '' || $to === '') { continue; }
            if (strpos($from, '<') !== false || strpos($from, '>') !== false) { continue; }

            // Avoid dangerous substring replacements such as Polish "po" inside "Post".
            if (preg_match('/^[\p{L}]+$/u', $from)) {
                $chars = preg_match_all('/./us', $from, $m);
                if ($chars !== false && $chars < 4) {
                    continue;
                }
            }

            $safe[$from] = $to;
        }

        return $safe;
    }

